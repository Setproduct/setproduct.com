import { Head, Html, Main, NextScript } from "next/document";

export default function Document() {
  return (
    <Html lang="en" data-scroll-behavior="smooth">
      <Head>
        {/* Generated by `npm run seo:assets`. WebP favicons are ignored by
            Safari and by the iOS home-screen bookmarks, and Android will not
            offer an install banner without a 192/512 PNG pair plus a manifest,
            which is exactly what the PWA audit was complaining about. */}
        <link href="/favicon.ico" rel="icon" sizes="32x32" />
        <link href="/images/favicon-32.png" rel="icon" sizes="32x32" type="image/png" />
        <link href="/images/favicon-16.png" rel="icon" sizes="16x16" type="image/png" />
        <link href="/images/apple-touch-icon.png" rel="apple-touch-icon" sizes="180x180" />
        <link href="/site.webmanifest" rel="manifest" />
        {/* Matches the white page background, so the browser chrome does not
            flash a default grey bar on mobile before the CSS arrives. */}
        <meta content="#ffffff" name="theme-color" />
        {/* The upright variable font is used on every page: fetch it with the CSS, not after it. */}
        <link
          href="/fonts/UncutSans-Variable.woff2"
          rel="preload"
          as="font"
          type="font/woff2"
          crossOrigin="anonymous"
        />
      </Head>
      <body>
        <Main />
        <NextScript />
      </body>
    </Html>
  );
}
